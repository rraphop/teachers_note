// 기록 줄바꿈 표시 규칙 시험 (3차 4번): node scripts/test-lines.mjs
// (Node 22.6+ 의 TypeScript 형식 제거로 src/lib/lines.ts 를 바로 읽는다)
import { splitLines } from "../src/lib/lines.ts";

let failed = 0;
const show = (ls) => ls.map((l) => (l.lead ? `[${l.lead}]` : "") + l.rest);
const eq = (name, text, want) => {
  const got = show(splitLines(text));
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) failed++;
  console.log(`${ok ? "OK " : "NG "} ${name}${ok ? "" : `\n    받음: ${JSON.stringify(got)}\n    기대: ${JSON.stringify(want)}`}`);
};

eq(
  "한 문단에 붙은 두 건 → 두 줄 (날짜·시각은 굵게)",
  "10. 6. 오전 9:30 경 OO교육지원청 학교지원센터에 강사수당 출처 물어봄, 담당자 홍길동, 000-000-0000. 10.6. 오전 9:40 경 OO군청 문화체육관광과에 참석 인원 물어봄",
  ["[10. 6. 오전 9:30] 경 OO교육지원청 학교지원센터에 강사수당 출처 물어봄, 담당자 홍길동, 000-000-0000.", "[10.6. 오전 9:40] 경 OO군청 문화체육관광과에 참석 인원 물어봄"],
);
eq("Enter 로 나눈 기록은 적은 그대로", "첫째 줄 내용\n둘째 줄 내용", ["첫째 줄 내용", "둘째 줄 내용"]);
eq("시각마다 줄바꿈", "09:36 1교시 시작 09:46 지각생 확인, 10:02 보건실 이동", ["[09:36] 1교시 시작", "[09:46] 지각생 확인,", "[10:02] 보건실 이동"]);
eq("기한으로 쓴 날짜는 나누지 않음", "보고서를 10월 10일까지 제출", ["보고서를 10월 10일까지 제출"]);
eq("시각 범위는 나누지 않음", "회의 9:30~10:30 본관", ["회의 9:30~10:30 본관"]);
eq("소수·전화번호는 날짜로 보지 않음", "평균 3.5점, 연락처 010-1234-5678", ["평균 3.5점, 연락처 010-1234-5678"]);
eq("10월 6일 앞에서 줄바꿈", "어제 회의 끝남 10월 6일 오후 3시 교직원 회의", ["어제 회의 끝남", "[10월 6일 오후 3시] 교직원 회의"]);
eq("빈 줄은 건너뜀", "가\n\n나", ["가", "나"]);
// 4차 2번: 문장 안에 들어간 시각은 나누지 않는다
eq("조사 뒤 시각은 한 줄", "오늘 교직원 점심은 12:20", ["오늘 교직원 점심은 12:20"]);
eq("시각 뒤 조사도 한 줄", "학생자치회는 15:15에 시작", ["학생자치회는 15:15에 시작"]);
eq("Enter 로 나눈 다음 줄은 그대로", "오늘 교직원 점심은 12:20\n2학년 홍길동 OO중 전학예정", ["오늘 교직원 점심은 12:20", "2학년 홍길동 OO중 전학예정"]);
eq("문장부호 뒤 시각은 새 항목", "교직원 회의 끝남. 15:15 학생자치회", ["교직원 회의 끝남.", "[15:15] 학생자치회"]);
console.log(failed ? `\n${failed}개 실패` : "\n모두 통과");
process.exit(failed ? 1 : 0);
