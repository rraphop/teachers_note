/** "0.2.1" → "0.21", "0.2.0" → "0.2" */
export function displayVersion(semver: string): string {
  const [major = "0", minor = "0", patch = "0"] = semver.split(".");
  return Number(patch) > 0 ? `${major}.${minor}${patch}` : `${major}.${minor}`;
}
